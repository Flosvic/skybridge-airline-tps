CREATE TABLE app_users (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100) NOT NULL,
 email VARCHAR2(254) UNIQUE NOT NULL,
 phone VARCHAR2(20) NOT NULL,
 password_hash VARCHAR2(200) NOT NULL,
 role VARCHAR2(10) DEFAULT 'CUSTOMER' NOT NULL CHECK (role IN ('CUSTOMER','ADMIN'))
);
CREATE TABLE app_sessions (
 token_hash VARCHAR2(64) PRIMARY KEY,
 user_id NUMBER NOT NULL REFERENCES app_users(id),
 expires_at TIMESTAMP NOT NULL
);
CREATE TABLE airlines (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 name VARCHAR2(80) UNIQUE NOT NULL,
 code VARCHAR2(4) UNIQUE NOT NULL
);
CREATE TABLE flights (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 airline_id NUMBER NOT NULL REFERENCES airlines(id),
 flight_no VARCHAR2(12) NOT NULL,
 origin VARCHAR2(3) NOT NULL,
 destination VARCHAR2(3) NOT NULL,
 departure_at TIMESTAMP NOT NULL,
 arrival_at TIMESTAMP NOT NULL,
 fare NUMBER(10,2) NOT NULL CHECK (fare > 0),
 capacity NUMBER(4) NOT NULL CHECK (capacity BETWEEN 1 AND 999),
 booked NUMBER(4) DEFAULT 0 NOT NULL,
 status VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL CHECK (status IN ('SCHEDULED','CANCELLED')),
 CHECK (origin <> destination), CHECK (arrival_at > departure_at),
 CHECK (booked BETWEEN 0 AND capacity), UNIQUE(flight_no, departure_at)
);
CREATE TABLE bookings (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 reference VARCHAR2(20) UNIQUE NOT NULL,
 user_id NUMBER NOT NULL REFERENCES app_users(id),
 flight_id NUMBER NOT NULL REFERENCES flights(id),
 passenger_name VARCHAR2(100) NOT NULL,
 amount NUMBER(10,2) NOT NULL,
 status VARCHAR2(20) DEFAULT 'AWAITING_PAYMENT' NOT NULL
 CHECK (status IN ('AWAITING_PAYMENT','PENDING_REVIEW','CONFIRMED','REJECTED','CANCELLED')),
 created_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
 reviewed_by NUMBER REFERENCES app_users(id),
 reviewed_at TIMESTAMP,
 review_note VARCHAR2(500)
);
CREATE TABLE payment_proofs (
 booking_id NUMBER PRIMARY KEY REFERENCES bookings(id),
 image_data BLOB NOT NULL,
 uploaded_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL
);
CREATE TABLE notifications (
 id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 booking_id NUMBER NOT NULL REFERENCES bookings(id),
 channel VARCHAR2(8) NOT NULL CHECK (channel IN ('EMAIL','SMS')),
 state VARCHAR2(12) DEFAULT 'QUEUED' NOT NULL
 CHECK (state IN ('QUEUED','PROCESSING','ACCEPTED','FAILED','SIMULATED','UNKNOWN')),
 detail VARCHAR2(250),
 updated_at TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
 UNIQUE(booking_id, channel)
);
CREATE INDEX bookings_flight_idx ON bookings(flight_id);
CREATE INDEX bookings_user_idx ON bookings(user_id);
CREATE INDEX sessions_user_idx ON app_sessions(user_id);
